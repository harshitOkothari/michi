#!/usr/bin/env bash
# Rebuilds js/bundle.js from the source files in js/.
#   bash build.sh
# - js/config.js is NOT part of the bundle (it's loaded on its own so your
#   keys never get overwritten by a rebuild).
# - If esbuild is available (npx esbuild) the bundle is minified — about half
#   the size, so the site loads faster. Without it you just get a plain bundle.
set -e
cd "$(dirname "$0")"

ORDER="db xp ui fx themes floattimer nudges auth profile friends admin games games2 games3 goals tests study tasks taskimport milestones fitness skills calendar history analysis dashboard app"
OUT=js/bundle.js
TMP=js/.bundle.tmp.js

{
  echo "// BUNDLE.JS — generated by build.sh from js/*.js. Edit the source files, then run: bash build.sh"
  for f in $ORDER; do
    echo ""
    echo "// ---- js/$f.js ----"
    cat "js/$f.js"
  done
} > "$TMP"

if command -v esbuild >/dev/null 2>&1; then
  esbuild "$TMP" --minify --format=iife --target=es2019 --outfile="$OUT" --log-level=warning
elif npx --no-install esbuild --version >/dev/null 2>&1; then
  npx --no-install esbuild "$TMP" --minify --format=iife --target=es2019 --outfile="$OUT" --log-level=warning
else
  cp "$TMP" "$OUT"
  echo "esbuild not found — wrote an unminified bundle. (Optional: npm i -g esbuild)"
fi
rm -f "$TMP"
echo "Built $OUT ($(wc -c < "$OUT") bytes)"
